async def seed_destinations():
    """Initializes tables and seeds all 35 sample destinations with distinct hero images."""
    await init_db()
    async with AsyncSessionLocal() as session:
        for item in SAMPLE_DESTINATIONS:
            res = await session.execute(select(Destination).where(Destination.id == item["id"]))
            existing = res.scalar_one_or_none()
            if not existing:
                dest = Destination(**item)
                session.add(dest)
            else:
                existing.name = item["name"]
                existing.country = item["country"]
                existing.region = item["region"]
                existing.lat = item["lat"]
                existing.lng = item["lng"]
                existing.iata_codes = item["iata_codes"]
                existing.timezone = item["timezone"]
                existing.description = item["description"]
                existing.wiki_title = item["wiki_title"]
                existing.hero_image_url = item["hero_image_url"]
                existing.hero_image_author = item["hero_image_author"]
                existing.hero_image_attribution = item["hero_image_attribution"]
        await session.commit()
    print(f"Seeded and updated {len(SAMPLE_DESTINATIONS)} curated destinations.")


if __name__ == "__main__":
    asyncio.run(seed_destinations())
